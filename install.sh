#!/bin/sh
# Sanket PTT v2 installer. Works on Raspberry Pi OS / Ubuntu arm64 and on x86_64 Ubuntu/Debian.
#   curl -fsSL https://raw.githubusercontent.com/vibhvesh/hyderabad-police-ptt/main/install.sh | sudo bash
# Optional: CLIENT_HOST=ptt.example.com ADMIN_HOST=admin.example.com
set -eu

ARCH_RAW=${SANKET_ARCH:-$(uname -m)}
case "$ARCH_RAW" in
  aarch64|arm64)
    ARCH_FAMILY=arm64
    ASR_PROVIDER=none
    ARCH_NOTE="This is a Raspberry Pi or other arm64 machine. Local Whisper is left off so the board stays light. After sign-in, open Settings and choose a cloud speech provider."
    ;;
  x86_64|amd64)
    ARCH_FAMILY=amd64
    ASR_PROVIDER=transformers
    ARCH_NOTE="This is an x86_64 server. Local Whisper is enabled. The first clip downloads a small model. You can switch to a cloud provider in Settings."
    ;;
  *)
    echo "This installer supports aarch64 (Raspberry Pi) and x86_64. This machine is $ARCH_RAW." >&2
    exit 1
    ;;
esac

if [ -n "${SANKET_INSTALL_ROOT:-}" ]; then
  ROOT=$SANKET_INSTALL_ROOT
elif [ -f "$PWD/docker-compose.yml" ] && [ -f "$PWD/install.sh" ]; then
  ROOT=$PWD
else
  ROOT=/opt/sanket-ptt
  if [ ! -f "$ROOT/docker-compose.yml" ]; then
    if ! command -v git >/dev/null 2>&1; then
      if command -v apt-get >/dev/null 2>&1; then
        apt-get update
        apt-get install -y git ca-certificates curl
      else
        echo "Install git, then run this again." >&2
        exit 1
      fi
    fi
    git clone --depth 1 https://github.com/vibhvesh/hyderabad-police-ptt.git "$ROOT"
  fi
fi

cd "$ROOT"
mkdir -p data
ENV_FILE=${SANKET_ENV_FILE:-$ROOT/.env}
CLIENT_URL_HOST=${CLIENT_HOST:-}
ADMIN_URL_HOST=${ADMIN_HOST:-}
PORT_VALUE=${PORT:-8080}

if [ ! -f "$ENV_FILE" ]; then
  ADMIN_VALUE=$(openssl rand -hex 24)
  SECRET_VALUE=$(openssl rand -hex 24)
  umask 077
  cat > "$ENV_FILE" <<EOF
# Generated by install.sh. Do not commit this file.
HOST=0.0.0.0
PORT=$PORT_VALUE
DATA_DIR=/data
PUBLIC_HOST=$CLIENT_URL_HOST
ADMIN_HOST=$ADMIN_URL_HOST
ADMIN_TOKEN=$ADMIN_VALUE
REVIEWER_TOKEN=$(openssl rand -hex 24)
INGEST_TOKEN=$(openssl rand -hex 24)
DEMO_ACCESS_CODE=
SECRETS_KEY=$SECRET_VALUE
ELEVENLABS_API_KEY=
ASR_PROVIDER=$ASR_PROVIDER
TRANSLATE_PROVIDER=none
TTS_PROVIDER=espeak
STT_DEFAULT=free
EOF
  echo "Wrote $ENV_FILE"
  echo "Admin token: $ADMIN_VALUE"
else
  echo "Keeping existing $ENV_FILE"
fi

if [ "${SANKET_SKIP_DOCKER:-}" = "1" ]; then
  echo "$ARCH_NOTE"
  echo "Docker start skipped."
else
  if ! command -v docker >/dev/null 2>&1; then
    echo "Installing Docker"
    curl -fsSL https://get.docker.com | sh
  fi
  if command -v systemctl >/dev/null 2>&1; then
    systemctl enable docker >/dev/null 2>&1 || true
    systemctl start docker >/dev/null 2>&1 || true
  fi
  docker compose up -d --build
  if command -v systemctl >/dev/null 2>&1 && [ -d /etc/systemd/system ]; then
    cat > /etc/systemd/system/sanket-ptt.service <<EOF
[Unit]
Description=Sanket PTT
After=docker.service
Requires=docker.service

[Service]
Type=oneshot
RemainAfterExit=yes
WorkingDirectory=$ROOT
ExecStart=/usr/bin/docker compose up -d
ExecStop=/usr/bin/docker compose stop
TimeoutStartSec=0

[Install]
WantedBy=multi-user.target
EOF
    systemctl daemon-reload >/dev/null 2>&1 || true
    systemctl enable sanket-ptt >/dev/null 2>&1 || true
  fi
fi

if [ -n "$CLIENT_URL_HOST" ]; then
  CLIENT_URL="https://$CLIENT_URL_HOST/"
else
  CLIENT_URL="http://127.0.0.1:$PORT_VALUE/#/"
fi
if [ -n "$ADMIN_URL_HOST" ]; then
  ADMIN_URL="https://$ADMIN_URL_HOST/"
else
  ADMIN_URL="http://127.0.0.1:$PORT_VALUE/#/control"
fi

echo
echo "Architecture: $ARCH_FAMILY ($ARCH_RAW)"
echo "$ARCH_NOTE"
echo "Client URL: $CLIENT_URL"
echo "Admin URL:  $ADMIN_URL"
echo
echo "Optional: put those hostnames on a Cloudflare Tunnel or Tailscale, then re-run with"
echo "  CLIENT_HOST=talk.example.com ADMIN_HOST=admin.example.com"
echo "Point both names at this machine's port $PORT_VALUE. This installer does not change a live tunnel."
